export function getIndustry(slug: string): Industry | undefined {
  return INDUSTRIES.find((i) => i.slug === slug);
}

export function getRelatedIndustries(currentSlug: string): Industry[] {
  const current = getIndustry(currentSlug);
  if (!current) return [];
  return INDUSTRIES.filter(
    (i) => i.slug !== currentSlug && i.relatedServices.some((s) => current.relatedServices.includes(s))
  ).slice(0, 4);
}
